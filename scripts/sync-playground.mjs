// Copies Claude-generated plans from apps/api/playground/out into the Remotion package
// and writes the index that registers them as Studio compositions (Playground-<name>).
import {copyFile, mkdir, readdir, rm, writeFile} from 'node:fs/promises';
import {join} from 'node:path';

const outDir = 'apps/api/playground/out';
const targetDir = 'packages/video/src/fixtures/playground';

const files = (await readdir(outDir)).filter((file) => file.endsWith('.scene.json'));
await mkdir(targetDir, {recursive: true});
for (const old of await readdir(targetDir)) if (old.endsWith('.json')) await rm(join(targetDir, old));

const entries = [];
for (const file of files) {
  const name = file.replace('.scene.json', '');
  const brandFile = `${name}.brand.json`;
  await copyFile(join(outDir, file), join(targetDir, file));
  await copyFile(join(outDir, brandFile), join(targetDir, brandFile));
  entries.push(name);
}

const ident = (name) => `p_${name.replace(/[^a-zA-Z0-9]/g, '_')}`;
const lines = [
  '// AUTO-GENERATED by scripts/sync-playground.mjs (npm run sync:playground). Do not edit by hand.',
  "import {brandKitSchema, type BrandKit} from '@ai-video-studio/schema';",
  ...entries.flatMap((name) => [`import ${ident(name)}_scene from './${name}.scene.json';`, `import ${ident(name)}_brand from './${name}.brand.json';`]),
  '',
  'export type PlaygroundEntry = {id: string; sceneJson: unknown; brand: BrandKit};',
  '',
  'export const playgroundEntries: PlaygroundEntry[] = [',
  ...entries.map((name) => `  {id: '${name}', sceneJson: ${ident(name)}_scene, brand: brandKitSchema.parse(${ident(name)}_brand)},`),
  '];',
  '',
];
await writeFile(join(targetDir, 'index.ts'), lines.join('\n'));
console.log(`Synced ${entries.length} playground scene(s): ${entries.join(', ') || '(none)'}`);
